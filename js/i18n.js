'use strict';
/*
 * Interface languages. The French text is the key: t('Bonjour') returns the French text as is,
 * or its English translation from EN. Everything is built in: no translation service, works offline.
 * What the user types (notes, names…) is never translated.
 */

const LANGS = { fr: 'Français', en: 'English' };
let LANG = 'fr';
let LOCALE = 'fr-FR';

const detectLang = () => (/^fr\b/i.test(navigator.language || '') ? 'fr' : 'en');

function setLang(lang) {
  LANG = LANGS[lang] ? lang : 'fr';
  LOCALE = LANG === 'fr' ? 'fr-FR' : 'en-US';
  document.documentElement.lang = LANG;
}

function t(key, params) {
  let s = LANG === 'en' ? (EN[key] ?? key) : key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
  return s;
}

